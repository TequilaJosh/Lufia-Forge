"""gen.py <clean US Lufia II ROM>: assembles extflags.asm and writes the C# data of the extra story flags patch
(LufiaForge/Core/Lufia2/L2ExtraFlags.Data.cs): the sites with the game's bytes they replace, the added block, and the
places holding a 24-bit address into the block (kept as the offset into it, filled in when the block has its place)."""
import os
import sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, '..', 'limits'))
from asm65 import assemble, lorom

rom = open(sys.argv[1], 'rb').read()
src = open(os.path.join(here, 'extflags.asm')).read()
A, B = 0x218000, 0x3FA000
ra, _ = assemble(src, {'HOOK': A})
rb, _ = assemble(src, {'HOOK': B})


def relocs(ba, bb):
    out, fixed = [], bytearray(ba)
    p = 0
    while p < len(ba):
        if ba[p] != bb[p]:
            for s in (p - 2, p - 1, p):
                if s < 0 or s + 3 > len(ba):
                    continue
                va = int.from_bytes(ba[s:s + 3], 'little') - A
                vb = int.from_bytes(bb[s:s + 3], 'little') - B
                if va == vb and 0 <= va < 0x8000:
                    out.append(s)
                    fixed[s:s + 3] = va.to_bytes(3, 'little')
                    p = s + 3
                    break
            else:
                raise SystemExit(f'unmatched difference at {p}: a 16-bit address into the block (use JSL / JML)')
        else:
            p += 1
    return out, bytes(fixed)


def hx(b):
    return ' '.join(f'{x:02X}' for x in b)


sites, block = [], None
for (addr, ba), (_, bb) in zip(ra, rb):
    rl, fixed = relocs(ba, bb)
    if addr == A:
        block = (fixed, rl)
        continue
    off = lorom(addr)
    orig = rom[off:off + len(ba)]
    if addr == 0x809B80 and orig != b'\xFF' * len(ba):
        raise SystemExit('$80:9B80 is not empty in this ROM')
    sites.append((off, addr, orig, fixed, rl))

lines = ['// Generated by tools/flags/gen.py from tools/flags/extflags.asm: do not edit by hand.',
         'namespace LufiaForge.Core.Lufia2;', '', 'public static partial class L2ExtraFlags', '{',
         '    private static readonly HookPatch.Site[] Sites =', '    {']
for off, addr, orig, fixed, rl in sites:
    r = ''.join(f', {p}' for p in rl)
    lines.append(f'        new(0x{off:05X}, "{hx(orig)}", "{hx(fixed)}"{r}),   // ${addr >> 16:02X}:{addr & 0xFFFF:04X}')
lines.append('    };')
fixed, rl = block
lines.append(f'    private static readonly HookPatch.Block Code = new("{hx(fixed)}"{"".join(f", {p}" for p in rl)});')
lines.append('}')
out = os.path.join(here, '..', '..', 'LufiaForge', 'LufiaForge', 'Core', 'Lufia2', 'L2ExtraFlags.Data.cs')
open(out, 'w', newline='\r\n').write('\n'.join(lines) + '\n')
print(f'{len(sites)} sites, block {len(fixed)} bytes, {len(rl)} relocations -> {os.path.normpath(out)}')
for off, addr, orig, fixed, rl in sites:
    print(f'  ${addr >> 16:02X}:{addr & 0xFFFF:04X}  {hx(orig):<30} -> {hx(fixed)}')
